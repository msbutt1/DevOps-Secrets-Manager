// Fails when src/types/openapi.gen.ts is out of date with docs/openapi.yaml.
// Fix with: npm run generate:api-types
import { readFileSync } from 'node:fs';
import openapiTS, { astToString } from 'openapi-typescript';
import * as prettier from 'prettier';

const target = 'src/types/openapi.gen.ts';
const spec = new URL('../../../docs/openapi.yaml', import.meta.url);

const header = '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n';
const generated = header + astToString(await openapiTS(spec));
const options = { ...(await prettier.resolveConfig(target)), filepath: target };
const fresh = await prettier.format(generated, options);

if (fresh !== readFileSync(target, 'utf8')) {
  console.error(`${target} is out of date with docs/openapi.yaml.`);
  console.error('Run `npm run generate:api-types` and commit the result.');
  process.exit(1);
}
console.log('Generated API types match docs/openapi.yaml');
